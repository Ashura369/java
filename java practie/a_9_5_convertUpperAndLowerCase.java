// converting a string into upper and lower case

public class a_9_5_convertUpperAndLowerCase {
    public static void main(String[] args) {
        String a = "Hello my name is jeet. I am from Odisha";

        // UPPERCASE
        String upper = a.toUpperCase();

        // lowercase
        String lower = a.toLowerCase();
        
        System.err.println(upper);
        System.err.println(lower);

        
    }
}
